import type { Genre } from "@/data/genres";

export type AnchorCategory =
  | "animals"
  | "plants"
  | "landscapes"
  | "weather"
  | "objects"
  | "buildings"
  | "food"
  | "occupations"
  | "phenomena"
  | "social";

export type Anchor = {
  id: string;
  label: string;
  category: AnchorCategory;
  genre: Genre;
  /** Higher = more likely. Default 1. */
  weight?: number;
};

export const ANCHOR_CATEGORIES: AnchorCategory[] = [
  "animals",
  "plants",
  "landscapes",
  "weather",
  "objects",
  "buildings",
  "food",
  "occupations",
  "phenomena",
  "social"
];

export const ANCHOR_CATEGORY_LABELS: Record<AnchorCategory, string> = {
  animals: "Animals",
  plants: "Plants",
  landscapes: "Landscapes",
  weather: "Weather",
  objects: "Objects",
  buildings: "Buildings",
  food: "Food",
  occupations: "Occupations",
  phenomena: "Phenomena",
  social: "Social"
};

function a(
  category: AnchorCategory,
  label: string,
  weight = 1,
  genre: Genre = "generic"
): Anchor {
  return {
    id: `${genre}:${category}:${label.toLowerCase().replace(/\s+/g, "-")}`,
    label,
    category,
    genre,
    weight
  };
}

